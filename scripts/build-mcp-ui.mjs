// Builds the Openfront MCP UI runtime (React + TuffUI) into public/images/mcp-ui/runtime.{js,css} and
// writes mcp-ui/server/version.ts. The MCP cards are tiny HTML pages that load these two files.
// Needs esbuild, which this repo does not depend on: ESBUILD_PATH=/path/to/node_modules/esbuild node scripts/build-mcp-ui.mjs
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { build } = require(process.env.ESBUILD_PATH ?? 'esbuild');
const postcss = require('postcss');
const tailwind = require('@tailwindcss/postcss');
mkdirSync(join(root, 'public/images/mcp-ui'), { recursive: true });
const js = await build({
  entryPoints: [join(root, 'mcp-ui/runtime/index.tsx')], bundle: true, minify: true, write: false, format: 'iife',
  target: 'es2020', jsx: 'automatic', legalComments: 'none', platform: 'browser', nodePaths: [join(process.env.NODE_MODULES_DIR ?? join(root, 'node_modules'))],
  define: { 'process.env.NODE_ENV': '"production"' }, alias: { '@': root },
});
const cssPath = join(root, 'mcp-ui/runtime/runtime.css');
const css = await postcss([tailwind()]).process(readFileSync(cssPath, 'utf8'), { from: cssPath });
const header = '/* Openfront MCP UI runtime. Includes TuffUI (https://tuffui.com, MIT, (c) 2026 TUFFUI contributors) and Phosphor icons (MIT). See THIRD_PARTY_NOTICES.md. Generated by scripts/build-mcp-ui.mjs. */\n';
const jsText = header + js.outputFiles[0].text, cssText = header + css.css;
writeFileSync(join(root, 'public/images/mcp-ui/runtime.js'), jsText);
writeFileSync(join(root, 'public/images/mcp-ui/runtime.css'), cssText);
const version = createHash('sha256').update(jsText).update(cssText).digest('hex').slice(0, 10);
writeFileSync(join(root, 'mcp-ui/server/version.ts'), `// Generated by scripts/build-mcp-ui.mjs. Do not edit.\nexport const MCP_UI_RUNTIME_VERSION = '${version}';\n`);
console.log(`runtime.js ${(jsText.length / 1024).toFixed(0)} KB, runtime.css ${(cssText.length / 1024).toFixed(0)} KB, v${version}`);
